"""Generate pb/tables.py: preflop equity of every starting-hand class vs a random hand.

Run once (offline):  python tools/gen_tables.py [samples_per_class]
Matrix layout: PF_EQ[r1][r2] with r1 >= r2 (rank 0=2 .. 12=A);
  r1 == r2 -> pair, suited hands stored at [r1][r2], offsuit at [r2][r1].
"""
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from pb.equity import equity  # noqa: E402


def main():
    n = int(sys.argv[1]) if len(sys.argv) > 1 else 30000
    rng = np.random.default_rng(2024)
    m = [[0.0] * 13 for _ in range(13)]
    for r1 in range(13):
        for r2 in range(r1 + 1):
            if r1 == r2:
                hole = (r1, 13 + r1)                 # c + d
                m[r1][r1] = equity(hole, (), None, n, rng)[0]
            else:
                suited = (r1, r2)                    # both clubs
                off = (r1, 13 + r2)                  # c + d
                m[r1][r2] = equity(suited, (), None, n, rng)[0]
                m[r2][r1] = equity(off, (), None, n, rng)[0]
    out = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), "pb", "tables.py")
    with open(out, "w") as f:
        f.write('"""AUTO-GENERATED by tools/gen_tables.py -- preflop equity vs a random hand.\n\n')
        f.write("PF_EQ[hi][lo] with hi>=lo : suited (or pair on the diagonal).\n")
        f.write('PF_EQ[lo][hi]            : offsuit.\n"""\n\nPF_EQ = [\n')
        for row in m:
            f.write("    [" + ", ".join("%.4f" % v for v in row) + "],\n")
        f.write("]\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
